package com.holzyn.actor.config;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

/**
 * Flyway「id 身份列（identity）」一致性校验（2026-10-23，玩家档案 500 轮追加）。
 *
 * <p>背景：设置页「玩家档案」打开即空白，根因是 <b>schema 漂移</b>——Hibernate 对 H2 的
 * IDENTITY 主键生成 {@code insert ... (..., id) values (..., default)}，依赖 id 列上有 identity
 * 默认值；而 12 张表是 Flyway 之前用历史 ddl-auto 时代建出来的（id 为裸 {@code bigint NOT NULL}），
 * 后来引入 Flyway 时这些库走 {@code baseline-on-migrate}（V1__baseline.sql 被标记已执行但未真正建表），
 * V1 里的 {@code id bigint generated by default as identity} 从未落到存量库上。实测：
 * {@code GET /api/player-profile} → HTTP 500 {@code NULL not allowed for column "id"}；
 * information_schema 中 112 个 id 列有 12 个 {@code is_identity=NO}，且这 12 张表当时全为 0 行
 * （对谈/助手/决策台账的首次写入从来没能成功过）。</p>
 *
 * <p>本仓库没有任何 {@code @SpringBootTest}（AGENTS.md §8.4-3），迁移写错只会在真实启动/真实
 * 首行插入时炸；因此这里用纯文件级断言把「实体要 identity ↔ 迁移必须给 identity」这条不变量钉住：</p>
 * <ol>
 * <li>{@code V7__repair_identity_columns.sql} 必须逐表修复实测漂移的 12 张表；</li>
 * <li>修复语句必须是 {@code alter table if exists ... generated by default as identity}
 * （缺表不炸迁移、已是 identity 时幂等、历史显式 id 仍可插入）；</li>
 * <li>V1 基线对这 12 张表本就声明了 identity（证明 V7 是「补回基线意图」而非另起结构）；</li>
 * <li>广义网：所有实体声明 {@code GenerationType.IDENTITY} 的表，其建表迁移必须带
 * {@code id bigint generated by default as identity} 或落在 V7 修复清单里。</li>
 * </ol>
 *
 * <p>所属模块：test/config（系统底层配置/迁移校验）</p>
 */
class FlywayIdentityColumnTest {

    /** V7 修复清单：2026-10-23 实测漂移的 12 张表（information_schema: is_identity=NO） */
    private static final List<String> DRIFTED_TABLES = List.of(
            "actor_talk_player_profile",
            "actor_talk_player_relation",
            "actor_talk_session",
            "actor_talk_message",
            "actor_talk_group_member",
            "actor_talk_worldbook",
            "actor_assistant_session",
            "actor_assistant_message",
            "actor_assistant_intervention",
            "actor_decision_log",
            "actor_decision_retry",
            "actor_world_engine_tick_stat");

    /** identity 列定义（V1 基线 / 建表迁移里的写法） */
    private static final String IDENTITY_COLUMN = "id bigint generated by default as identity";

    /** V7 修复语句单条形态（表名占位） */
    private static final String REPAIR_TPL =
            "alter table if exists %s alter column id bigint generated by default as identity";

    /** 读 classpath 下的 SQL 文件为文本（V1.1.2 起历史迁移归档到 db/legacy） */
    private static String sqlText(String relative) throws IOException {
        ClassPathResource res = new ClassPathResource("db/" + relative);
        assertTrue(res.exists(), "SQL 文件缺失：db/" + relative);
        try (var in = res.getInputStream()) {
            return new String(in.readAllBytes(), StandardCharsets.UTF_8);
        }
    }

    /** 去注释、去空行、压平空白（便于逐语句比对） */
    private static String normalize(String sql) {
        StringBuilder sb = new StringBuilder();
        for (String line : sql.split("\\R")) {
            String trimmed = line.trim();
            if (trimmed.isEmpty() || trimmed.startsWith("--")) {
                continue;
            }
            sb.append(trimmed).append(' ');
        }
        return sb.toString().replaceAll("\\s+", " ").trim().toLowerCase(Locale.ROOT);
    }

    /** 拆语句（按分号；迁移里没有存储过程体，简单切分即可） */
    private static List<String> statements(String sql) {
        List<String> out = new ArrayList<>();
        for (String part : normalize(sql).split(";")) {
            String s = part.trim();
            if (!s.isEmpty()) {
                out.add(s);
            }
        }
        return out;
    }

    /** 取迁移文本里某表的建表语句（到分号为止；兼容 `create table [if not exists] x` 两种写法） */
    private static String createTableStatement(String normalizedSql, String table) {
        Matcher m = Pattern.compile("create table (?:if not exists )?" + Pattern.quote(table) + "\\b")
                .matcher(normalizedSql);
        if (!m.find()) {
            return null;
        }
        int start = m.start();
        int end = normalizedSql.indexOf(';', start);
        return end < 0 ? normalizedSql.substring(start) : normalizedSql.substring(start, end);
    }

    @Test
    @DisplayName("V7：实测漂移的 12 张表逐条修复，且语句为『if exists + generated by default』安全形态")
    void v7RepairsEveryDriftedTable() throws IOException {
        List<String> stmts = statements(sqlText("legacy/V7__repair_identity_columns.sql"));
        assertFalse(stmts.isEmpty(), "V7 迁移内容为空");

        Set<String> repaired = new LinkedHashSet<>();
        for (String stmt : stmts) {
            assertTrue(stmt.startsWith("alter table if exists "),
                    "V7 语句必须以 `alter table if exists` 开头（老库缺表时不能炸迁移）：" + stmt);
            assertTrue(stmt.endsWith(IDENTITY_COLUMN),
                    "V7 语句必须补 `" + IDENTITY_COLUMN + "`：" + stmt);
            assertFalse(stmt.contains("generated always"),
                    "必须用 generated by default（历史显式 id 仍可插入），不能用 generated always：" + stmt);
            Matcher m = Pattern.compile("alter table if exists (\\w+) ").matcher(stmt);
            assertTrue(m.find(), "无法解析 V7 语句表名：" + stmt);
            repaired.add(m.group(1));
        }
        assertTrue(repaired.equals(new LinkedHashSet<>(DRIFTED_TABLES)),
                "V7 修复表清单应与实测漂移清单完全一致，实际=" + repaired);
        for (String table : DRIFTED_TABLES) {
            assertTrue(stmts.contains(REPAIR_TPL.formatted(table)), "V7 缺少对该表的修复：" + table);
        }
    }

    @Test
    @DisplayName("V1 基线：漂移的 12 张表本就声明 identity（V7 是补回基线意图）")
    void baselineAlreadyDeclaresIdentityForDriftedTables() throws IOException {
        String baseline = normalize(sqlText("legacy/V1__baseline.sql"));
        for (String table : DRIFTED_TABLES) {
            String ddl = createTableStatement(baseline, table);
            assertTrue(ddl != null, "V1 基线缺少建表语句：" + table);
            assertTrue(ddl.contains(IDENTITY_COLUMN),
                    "V1 基线该表未声明 identity（则 V7 的修复目标不自洽）：" + table + " → " + ddl);
        }
    }

    @Test
    @DisplayName("广义网：每个 IDENTITY 实体表的建表迁移必须给出 identity，或由 V7 修复")
    void everyIdentityEntityTableGetsIdentityFromMigrations() throws IOException {
        Path sourceRoot = Path.of("src/main/java");
        assumeTrue(Files.isDirectory(sourceRoot), "非 maven 后端根目录，跳过源码扫描");

        // 实体侧：@Table(name="x") + GenerationType.IDENTITY
        Pattern tablePattern = Pattern.compile("@Table\\s*\\([^)]*?name\\s*=\\s*\"([^\"]+)\"", Pattern.DOTALL);
        Set<String> identityTables = new LinkedHashSet<>();
        try (Stream<Path> files = Files.walk(sourceRoot)) {
            for (Path p : files.filter(f -> f.toString().endsWith(".java")).toList()) {
                String src = Files.readString(p, StandardCharsets.UTF_8);
                if (!src.contains("GenerationType.IDENTITY")) {
                    continue;
                }
                Matcher m = tablePattern.matcher(src);
                if (m.find()) {
                    identityTables.add(m.group(1).toLowerCase(Locale.ROOT));
                }
            }
        }
        assertFalse(identityTables.isEmpty(), "未扫描到任何 IDENTITY 实体（扫描逻辑失效）");

        // 迁移侧：全部历史迁移文本（V1~V7，V1.1.2 起归档在 db/legacy）
        StringBuilder all = new StringBuilder();
        try (Stream<Path> files = Files.list(Path.of("src/main/resources/db/legacy"))) {
            for (Path p : files.sorted().toList()) {
                if (p.toString().endsWith(".sql")) {
                    all.append(normalize(Files.readString(p, StandardCharsets.UTF_8))).append('\n');
                }
            }
        }
        String migrations = all.toString();
        // V200 之后的新表只能走增量迁移（改基线会改 checksum → 已有世界起不来）；
        // 实体扫描看不到「分批存放」这件事，所以增量 SQL 必须并进来一起判 identity。
        migrations += "\n" + normalize(WorldIncrementTables.incrementSql());

        List<String> broken = new ArrayList<>();
        for (String table : identityTables) {
            // 实体用改名后的新名，历史上以单一模型命名的表在 db/legacy 里仍是旧名（改名由 V203/迁移器收口）
            String migrated = WorldSchemaRenames.baselineNameOf(table);
            String ddl = createTableStatement(migrations, migrated);
            boolean identityInCreate = ddl != null && ddl.contains(IDENTITY_COLUMN);
            boolean repairedByV7 = migrations.contains(REPAIR_TPL.formatted(migrated));
            if (!identityInCreate && !repairedByV7) {
                broken.add(table);
            }
        }
        assertTrue(broken.isEmpty(),
                "以下表由 IDENTITY 实体写入，但迁移没给 identity（首行插入必 500）：" + broken);
    }
}
