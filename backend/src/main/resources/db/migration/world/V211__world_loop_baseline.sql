-- V211：角色↔世界闭环地基（§4.4.1）
--
-- 为什么是 V211 而不是文档里的 V210：V210 已被「时间性验证探针」（
-- V210__temporal_audit_probe.sql）占用；Flyway 版本号不可复用，故顺延到 V211。
-- 物品域（文档 §4.4.5 的 V211）将来顺延到 V212。
--
-- 本迁移只做「新增」：新列全部带默认值、新表全部 if not exists，
-- 旧世界打开时由 Flyway 自动补列/建表；不 drop、不改列类型。
-- 对应开关 holzyn.actor.world-loop.enabled 默认 false —— 迁移本身不改变任何既有行为。
-- ============================================================================

-- ---------------------------------------------------------------- ① 玩家同构
-- controller：npc（缺省）/ player；旧行自动落 npc，行为不变。
-- player_user_id：玩家实体与登录账户的绑定（唯一索引允许多个 NULL，不影响 NPC 行）。
alter table actor_profile add column if not exists controller varchar(12) default 'npc' not null;
alter table actor_profile add column if not exists player_user_id varchar(64);
create index if not exists ix_profile_controller on actor_profile (project_id, controller);
create unique index if not exists ux_profile_player on actor_profile (project_id, player_user_id);

-- ---------------------------------------------------------------- ② 事件因果
-- cause_event_id：直接原因事件；correlation_id：一条因果链的根标识（根事件=自身 id）；
-- depth：链深（根=0，子=父+1），用于「depth ≤ 6」与前端树形展开。
alter table actor_event add column if not exists cause_event_id bigint;
alter table actor_event add column if not exists correlation_id varchar(40);
alter table actor_event add column if not exists depth integer default 0 not null;
create index if not exists ix_event_correlation on actor_event (correlation_id);
create index if not exists ix_event_cause on actor_event (cause_event_id);

-- ---------------------------------------------------------------- ③ 行动裁决
-- 一次行动本来就是 actor_plan 的一行，「结果」是它的属性（不新建 outcome 表）。
alter table actor_plan add column if not exists verdict varchar(12);
alter table actor_plan add column if not exists reason_code varchar(40);
alter table actor_plan add column if not exists effects_json TEXT;
alter table actor_plan add column if not exists event_id bigint;

-- ---------------------------------------------------------------- ④ 信息包溯源
alter table actor_info_packet add column if not exists source_event_id bigint;
alter table actor_info_packet add column if not exists subject_ref varchar(64);
alter table actor_info_packet add column if not exists fact_key varchar(120);
create index if not exists ix_info_packet_source on actor_info_packet (source_event_id);

-- ---------------------------------------------------------------- ⑤ 事实层（状态）
-- 事件=「发生过」，事实=「现在怎样」；叙事（actor_world_entity）与状态分表，
-- 否则裁决器要解析自然语言才知道「还剩几袋麦子」。
create table if not exists actor_world_fact (
    id bigint generated by default as identity,
    project_id bigint not null,
    fact_type varchar(24) not null,
    fact_key varchar(120) not null,
    name varchar(200),
    state_text varchar(500) not null,
    attributes_json TEXT,
    location_id bigint,
    location_name varchar(100),
    visibility varchar(12) not null,
    authority varchar(8) default 'brain' not null,
    version integer default 1 not null,
    valid_from_game_second bigint,
    valid_to_game_second bigint,
    status varchar(12) default 'active' not null,
    source_event_id bigint,
    created_at timestamp(6),
    updated_at timestamp(6),
    primary key (id)
);
create unique index if not exists ux_fact_key on actor_world_fact (project_id, fact_key);
create index if not exists ix_fact_loc on actor_world_fact (project_id, location_name, status);
create index if not exists ix_fact_type on actor_world_fact (project_id, fact_type, status);
create index if not exists ix_fact_authority on actor_world_fact (project_id, authority, status);

-- 事实变更日志：每次变化一条（create/update/expire/void），source_event_id 必填。
create table if not exists actor_world_fact_log (
    id bigint generated by default as identity,
    project_id bigint not null,
    fact_id bigint not null,
    fact_key varchar(120) not null,
    version integer not null,
    op varchar(8) not null,
    before_json TEXT,
    after_json TEXT,
    delta_json TEXT,
    game_second bigint,
    actor_ref varchar(64),
    writer varchar(12),
    event_id bigint,
    idempotency_key varchar(80),
    created_at timestamp(6),
    primary key (id)
);
create unique index if not exists ux_factlog_idem on actor_world_fact_log (project_id, idempotency_key);
create index if not exists ix_factlog_fact on actor_world_fact_log (fact_id, version);

-- 认知层：谁知道这条事实、怎么知道、多可信（决策只读 knowledge，不读全项目事实）。
create table if not exists actor_world_fact_knowledge (
    id bigint generated by default as identity,
    project_id bigint not null,
    fact_id bigint not null,
    knower_ref varchar(64) not null,
    learned_game_second bigint,
    source_type varchar(12) not null,
    source_ref varchar(64),
    confidence integer default 100 not null,
    distortion_json TEXT,
    created_at timestamp(6),
    primary key (id)
);
create unique index if not exists ux_factknow on actor_world_fact_knowledge (project_id, fact_id, knower_ref);
create index if not exists ix_factknow_ref on actor_world_fact_knowledge (project_id, knower_ref, learned_game_second);

-- ---------------------------------------------------------------- ⑥ 权威模式状态
-- 每个世界一行：当前权威模式、引擎最后 seq、交接时间、drift。
-- 桌面端（无引擎）恒 brain；接引擎时由 WorldLifecycleService.open 落定。
create table if not exists actor_world_authority_state (
    project_id bigint not null,
    mode varchar(12) not null,
    last_engine_seq bigint,
    last_engine_connected_at timestamp(6),
    last_handover_at timestamp(6),
    last_game_second bigint,
    drift_json TEXT,
    updated_at timestamp(6),
    primary key (project_id)
);
