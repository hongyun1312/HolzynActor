-- ============================================================================
-- V215：物品域耐久腐坏装备（§4.4.5 / §8.2）
--
-- 本迁移做四件事：
--   ① 把 actor_item_stack.durability 从「可空占位列」变成真正的状态列
--      （必填、默认 100），并加「新鲜锚点」fresh_at_game_second；
--   ② 唯一索引加上 durability —— 让「同一件物品的不同磨损层」可以并存，
--      这是「一把刀用旧了」与「另一把还是新的」能同时存在的物理前提；
--   ③ 建 actor_item_equipment —— 谁身上/手上戴着什么（装备槽）；
--   ④ 播种全局物品定义（project_id=0）并把历史上「懒建」出来的占位定义升级。
--
-- 为什么 ② 必须改索引而不是「把磨损记在层上」：
--   V212 的唯一索引是 (project_id, holder_ref, item_key, quality)，一个层里放 N 件。
--   若磨损只改层上的 durability，5 把刀会「一起变钝、一起断」——那是假的。
--   把 durability 并入唯一键后，磨损一件 = 从 (品质,耐久 100) 层里挪 1 件到
--   (品质,耐久 99) 层，逐件真实，且仍然满足「同状态堆叠合并」。
--   durability 因此必须 NOT NULL（NULL 在 H2 唯一索引里是 NULLS DISTINCT，
--   多个 NULL 会被当成互不相同，唯一性对不腐坏/不磨损的物品就失效了）。
--
-- 为什么 ④ 要顺手升级懒建定义：宽松策略把任何没登记过的键懒建成
--   material/99/0，柴刀也不例外——不升级的话「柴刀」永远不是武器、不能装备，
--   也不会腐坏。懒建行的签名是 name = item_key（从未被显式命名过），只按这个签名升级，
--   显式定义过的行（project_id>0 且 name 与键不同）一律不动。
--
-- 权威与开关：本迁移不改变任何既有行为。holzyn.actor.wear.enabled 默认 false，
-- 关闭时既没有腐坏 tick、也不解析装备，R-ATTACK-01 走 「身上有武器即算」旧路径。
-- ============================================================================

-- ---------------------------------------------------------------- ① 耐久成为真状态
-- 历史行 durability 全为 NULL（从未写过）；先补 100 再收紧约束。
update actor_item_stack set durability = 100 where durability is null;
alter table actor_item_stack alter column durability set default 100;
alter table actor_item_stack alter column durability set not null;
alter table actor_item_stack add constraint if not exists ck_itemstack_durability
    check (durability >= 0 and durability <= 100);

-- 新鲜锚点：这件（批）东西「什么时候还算新鲜的」（游戏秒）。
-- 腐坏不按现实时间推进，也不按「上次结算到现在累加小数」——而是每次都用
-- 质量 = 100 - floor(100 × (now - fresh_at) / (decay_hours × 3600)) 现算，
-- 于是同一游戏秒重复结算得到同一个质量（幂等、可复算、不会因四舍五入漂移）。
-- 为空 = 还没被腐坏逻辑碰过（首次 tick 时补成当前游戏秒）。
alter table actor_item_stack add column if not exists fresh_at_game_second bigint;

-- ---------------------------------------------------------------- ② 唯一索引加 durability
drop index if exists ux_itemstack;
create unique index if not exists ux_itemstack
    on actor_item_stack (project_id, holder_ref, item_key, quality, durability);

-- ---------------------------------------------------------------- ③ 装备槽
-- 一行 = 某持有者某个槽位上「在用」的那件东西。
-- 只记 item_key，不复制 quality/durability：磨损与品质的唯一真相是持有栈，
-- 装备行若另存一份，两边迟早对不上（卖了/吃了/烂了，装备行还挂着）。
-- 读的时候按 item_key 在背包里找「最好的一层」= 手上这件；找不到就自愈删除。
-- 槽位：hand（手持/武器）、body（穿戴）。槽位取值由物品定义的 equip_slot 决定，
-- 这里不再单列一张槽位表——多一张表就多一个要同步的目录。
create table if not exists actor_item_equipment (
    id bigint generated by default as identity,
    project_id bigint not null,
    holder_ref varchar(64) not null,
    slot varchar(16) not null,
    item_key varchar(60) not null,
    since_game_second bigint,
    updated_at timestamp(6),
    primary key (id)
);
-- 一个槽位同时只能有一件东西
create unique index if not exists ux_equipment_slot
    on actor_item_equipment (project_id, holder_ref, slot);
-- 「谁身上有这件装备」（清理/对账用）
create index if not exists ix_equipment_item on actor_item_equipment (project_id, item_key);

