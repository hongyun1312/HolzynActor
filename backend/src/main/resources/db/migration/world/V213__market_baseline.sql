-- V213：市场交易地基（§4.7 R-TRADE-01/02 / §8.2）
--
-- 两张新表：报价（actor_market_quote）与流水（actor_market_trade）。全部
-- if not exists，旧世界打开时由 Flyway 自动建表；不 drop、不改既有表。
-- 从属于 holzyn.actor.item.enabled：物品域关闭时 InventoryPort 不装配，
-- 本表不会被写（MarketService 直接拒绝），迁移本身不改变任何既有行为。
--
-- 货币口径：货币就是物品（actor_item_stack 一行），默认 item_key=coin。
-- 为什么不做钱包表：物品域已有账本、幂等、无负库存三套保证；再加一套钱包
-- 就是第二本账（同一件事两个写入口），对账必然漂移。
-- ============================================================================

-- ---------------------------------------------------------------- ① 市场报价
-- 一行 = 一个 (卖家, 物品) 的当前报价。价格由供需记分卡给出：
--   supply_qty  报价时的货架存量
--   demand_qty  需求窗口（market.demand-window-days）内的成交量
--   price_factor 价格因子（基准价 × 因子 = 单价），与宏观粮价同一套公式
-- 唯一索引保证「一个卖家一种货只有一个当前价」，历史价留在流水里。
create table if not exists actor_market_quote (
    id bigint generated by default as identity,
    project_id bigint not null,
    seller_ref varchar(64) not null,
    item_key varchar(60) not null,
    base_price integer default 0 not null,
    unit_price integer default 0 not null,
    supply_qty integer default 0 not null,
    demand_qty integer default 0 not null,
    price_factor numeric(6,3) default 1.000 not null,
    quote_game_second bigint,
    version integer default 1 not null,
    updated_at timestamp(6),
    primary key (id)
);
create unique index if not exists ux_marketquote on actor_market_quote (project_id, seller_ref, item_key);
create index if not exists ix_marketquote_seller on actor_market_quote (project_id, seller_ref);
-- 价格不允许为负：真实世界里没有「倒贴钱的柜台」，负价只可能是公式写错
alter table actor_market_quote add constraint if not exists ck_marketquote_price
    check (base_price >= 0 and unit_price >= 0 and supply_qty >= 0 and demand_qty >= 0);

-- ---------------------------------------------------------------- ② 交易流水
-- 一笔成交一条；idempotency_key 唯一（同一效果重放不重复扣货、不重复收钱）。
-- paid / on_credit / settled 三个口径：
--   现金：paid=true  on_credit=false settled=true
--   赊账：paid=false on_credit=true  settled=false（欠款待还，还款由后续阶段接线）
-- 金额口径：unit_price 是成交单价（元/件），total_price = unit_price × qty。
create table if not exists actor_market_trade (
    id bigint generated by default as identity,
    project_id bigint not null,
    seller_ref varchar(64) not null,
    buyer_ref varchar(64) not null,
    item_key varchar(60) not null,
    qty integer not null,
    unit_price integer default 0 not null,
    total_price integer default 0 not null,
    currency_key varchar(60) not null,
    paid boolean default true not null,
    on_credit boolean default false not null,
    settled boolean default true not null,
    reason varchar(32),
    event_id bigint,
    game_second bigint,
    idempotency_key varchar(80),
    created_at timestamp(6),
    primary key (id)
);
-- NULL 幂等键在 H2 下互不相同（NULLS DISTINCT），不带键的内部成交可多条共存
create unique index if not exists ux_markettrade_idem on actor_market_trade (project_id, idempotency_key);
create index if not exists ix_markettrade_seller on actor_market_trade (project_id, seller_ref, game_second);
create index if not exists ix_markettrade_buyer on actor_market_trade (project_id, buyer_ref, game_second);
-- 严格「没有就是没有」：成交数量与金额不允许为负
alter table actor_market_trade add constraint if not exists ck_markettrade_amount
    check (qty > 0 and unit_price >= 0 and total_price >= 0);
