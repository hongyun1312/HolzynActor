-- V214：物品域制作与建造（§4.4.5 / §8.2）
--
-- 本迁移做三件事，全部「只增不改」：
--   ① 给 actor_item_recipe 补 3 列（V212 建表时按§4.4.5 的字段清单建的，
--      缺「产出形态」与「启停」，制作/建造要区分「产物进背包」与「产物落成世界里的设施」）；
--   ② 建 actor_craft_job —— 一件活的计时与状态（开工扣料、到点出产物、可被打断）；
--   ③ 播种全局配方目录（project_id=0），让世界一打开就有「能做成的东西」。
--
-- 为什么配方目录写在迁移里而不是启动时用 Java 播种：
--   actor_item_recipe 是「世界库」的表，每个世界库一份；V214 在每个世界库各跑一次，
--   正好等价于「每个世界都有一份全局模板」。若改用 ApplicationRunner 播种，就会在
--   CraftService 之外出现第二个写 actor_item_recipe 的入口（违反 AGENTS §8.1.4 单一写入口）。
--   配方行 project_id=0 是模板，某个世界要改自己的配方时写 project_id>0 的同名行覆盖即可
--   （查找顺序：本项目 → 全局模板，与 actor_item_def 的两级查找同构）。
--
-- 权威与开关：本迁移不改变任何既有行为。holzyn.actor.craft.enabled 默认 false，
-- 关闭时 R-CRAFT-01 保持「配方未知」UNSURE，与之前逐字节一致。
-- ============================================================================

-- ---------------------------------------------------------------- ① 配方补列
-- output_kind：item=产物进背包（制作）/ facility=产物成为一处设施（建造）/
--              prop=产物成为场景物件（建造）。默认 item，既有行语义不变。
alter table actor_item_recipe add column if not exists output_kind varchar(12) default 'item' not null;
-- enabled：某世界想临时停做某样东西时置 false，不必删行（删行会丢「曾经会做」的记忆）
alter table actor_item_recipe add column if not exists enabled boolean default true not null;
alter table actor_item_recipe add column if not exists updated_at timestamp(6);
alter table actor_item_recipe add constraint if not exists ck_recipe_qty
    check (output_qty > 0 and duration_minutes >= 0);

-- ---------------------------------------------------------------- ② 制作作业
-- 一行 = 一件活。开工即扣材料（材料已经投进去，半途放弃就废了），产物在
-- finish_game_second 到点后由结算扫描产出；status 是唯一的进度真相。
-- 为什么不做「材料到点才扣」：那样两个角色能同时开工抢同一批料，最后谁先到点谁成功，
-- 世界会出现「料只够一份却做出两件」——严格「没有就是没有」要求开工即扣。
create table if not exists actor_craft_job (
    id bigint generated by default as identity,
    project_id bigint not null,
    actor_ref varchar(64) not null,
    recipe_key varchar(60) not null,
    output_item_key varchar(60) not null,
    output_kind varchar(12) default 'item' not null,
    output_qty integer default 1 not null,
    batches integer default 1 not null,
    facility_type varchar(24),
    facility_ref varchar(64),
    location_id bigint,
    location_name varchar(120),
    started_game_second bigint not null,
    finish_game_second bigint not null,
    status varchar(16) default 'in_progress' not null,
    reason varchar(64),
    event_id bigint,
    idempotency_key varchar(80),
    created_at timestamp(6),
    updated_at timestamp(6),
    primary key (id)
);
-- 同一效果重放不重复开工
create unique index if not exists ux_craftjob_idem on actor_craft_job (project_id, idempotency_key);
-- 结算扫描：status + finish_game_second 是最热的查询条件
create index if not exists ix_craftjob_due on actor_craft_job (project_id, status, finish_game_second);
-- 「这个人手上还有没有活」（R-CRAFT-01 BUSY 判定）
create index if not exists ix_craftjob_actor on actor_craft_job (project_id, actor_ref, status);
-- 严格计数：批次与单批产出必须为正，否则产出量会算成 0 或负数
alter table actor_craft_job add constraint if not exists ck_craftjob_qty
    check (batches > 0 and output_qty > 0);
-- 时间必须向前（到点早于开工等于「立刻完成」，会让耗时形同虚设）
alter table actor_craft_job add constraint if not exists ck_craftjob_time
    check (finish_game_second >= started_game_second);

