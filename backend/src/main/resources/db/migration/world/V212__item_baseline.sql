-- ---------------------------------------------------------------- ① 物品定义
-- project_id = 0 表示「全局模板」，>0 表示该世界的覆盖定义。
-- 为什么用 0 而不是 NULL：H2 唯一索引默认 NULLS DISTINCT，多个 NULL 会被当成互不
-- 相同，(project_id, item_key) 的唯一性对全局模板就失效了；用 0 哨兵让约束真正生效，
-- 同时保留「先查本项目、再回退全局」的两级查找。
create table if not exists actor_item_def (
    id bigint generated by default as identity,
    project_id bigint default 0 not null,
    item_key varchar(60) not null,
    name varchar(120) not null,
    category varchar(24) not null,
    stack_max integer default 99 not null,
    unit_weight numeric(10,2) default 0,
    base_price integer default 0 not null,
    decay_hours integer,
    equip_slot varchar(16),
    attributes_json TEXT,
    primary key (id)
);
create unique index if not exists ux_itemdef on actor_item_def (project_id, item_key);
create index if not exists ix_itemdef_key on actor_item_def (item_key);

-- ---------------------------------------------------------------- ② 持有栈
-- holder_ref 命名空间：npc:{profileId}（含 controller=player 的玩家行）、
-- loc:{locationId}（地点货架/仓廪）、container:{placementId}（将来的容器）。
-- 一行 = 一个 (持有者, 物品, 品质) 层；quantity 是该层的总数。
-- 为什么唯一索引带 quality：不同品质不能合并，否则「这把刀八成新」会被抹平。
create table if not exists actor_item_stack (
    id bigint generated by default as identity,
    project_id bigint not null,
    holder_ref varchar(64) not null,
    item_key varchar(60) not null,
    quantity integer not null,
    quality integer default 100 not null,
    durability integer,
    version integer default 1 not null,
    source_event_id bigint,
    updated_at timestamp(6),
    primary key (id)
);
create unique index if not exists ux_itemstack on actor_item_stack (project_id, holder_ref, item_key, quality);
create index if not exists ix_itemstack_holder on actor_item_stack (project_id, holder_ref);
-- 严格「没有就是没有」：数量不允许为负（决策 A，避免透支记账污染世界）
alter table actor_item_stack add constraint if not exists ck_itemstack_qty check (quantity >= 0);

-- ---------------------------------------------------------------- ③ 物品账本
-- 每次数量变化一条，idempotency_key 唯一（同一效果重放不翻倍）。
-- qty_delta 口径：转移记正数（配合 from_ref/to_ref 表方向）；产出记 +qty；消耗记 -qty。
create table if not exists actor_item_ledger (
    id bigint generated by default as identity,
    project_id bigint not null,
    item_key varchar(60) not null,
    qty_delta integer not null,
    from_ref varchar(64),
    to_ref varchar(64),
    reason varchar(32) not null,
    writer varchar(12),
    event_id bigint,
    game_second bigint,
    idempotency_key varchar(80),
    created_at timestamp(6),
    primary key (id)
);
-- NULL 幂等键在 H2 下互不相同（NULLS DISTINCT），因此「不带键的内部变更」可以多条共存
create unique index if not exists ux_ledger_idem on actor_item_ledger (project_id, idempotency_key);
create index if not exists ix_ledger_item on actor_item_ledger (project_id, item_key, game_second);

-- ---------------------------------------------------------------- ④ 配方（使用）
-- 只建表不写入；制作/建造时读 inputs_json 判材料是否齐（R-CRAFT-01）。
create table if not exists actor_item_recipe (
    id bigint generated by default as identity,
    project_id bigint default 0 not null,
    recipe_key varchar(60) not null,
    output_item_key varchar(60) not null,
    output_qty integer default 1 not null,
    inputs_json TEXT not null,
    facility_type varchar(24),
    duration_minutes integer default 30,
    primary key (id)
);
create unique index if not exists ux_recipe on actor_item_recipe (project_id, recipe_key);
