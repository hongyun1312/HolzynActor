-- 时间性验证：探针结果表（审计层唯一写入口）
-- 只增不改：探针结果按批次留档，报告现算不落快照（见5.1）。
CREATE TABLE IF NOT EXISTS actor_temporal_probe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    run_tag VARCHAR(64),
    probe_type VARCHAR(24) NOT NULL,
    variant VARCHAR(24) NOT NULL,
    character_ref VARCHAR(64),
    character_id BIGINT,
    game_second BIGINT,
    game_day BIGINT,
    question TEXT,
    evidence_snapshot TEXT,
    expected_json TEXT,
    answer_raw TEXT,
    answer_json TEXT,
    verdict VARCHAR(16),
    assertion_detail TEXT,
    prompt_len INT,
    latency_ms INT,
    trace_id VARCHAR(64),
    created_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_temporal_probe_proj_gs ON actor_temporal_probe (project_id, game_second);
CREATE INDEX IF NOT EXISTS idx_temporal_probe_type ON actor_temporal_probe (project_id, probe_type, verdict);
