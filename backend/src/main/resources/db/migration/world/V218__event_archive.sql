-- =====================================================================
-- V218：事件表冷存储（事件不再被滚动淘汰「冲掉」）
--
-- 背景：澄江镇二日实跑里 actor_event 全程恒为 5000 条——事件总线每发布一条，
-- 超限就把最旧的一条物理删除。于是「叙事原料」（编年史提炼、时间线回放、
-- 角色经历）与「审计证据」（谁在什么时候做了什么）在两天内就被冲刷了一遍。
--
-- 为什么不是简单调大上限：热表是每次发布都要 count 的，也是时间线/感知查询的主表；
-- 把它撑到十万级换取「不丢」，代价落在每一次查询上。真正的语义是
-- 「近期事件要快查，旧事件要留得住」——所以拆冷热：热表仍按上限滚动，
-- 淘汰前逐行搬进冷表（同一事务，先归档后删除；归档失败则不删，宁可胀不丢）。
--
-- 与 actor_memory_archive / actor_world_chronicle_archive 同一定位，
-- 命名与列口径保持一致（*_archive = 只追加、不参与业务查询）。
-- =====================================================================

create table if not exists actor_event_archive (
    id bigint generated by default as identity,
    -- 原事件主键（业务可追溯；不设外键，冷表不参与约束）
    event_id bigint not null,
    project_id bigint not null,
    kind varchar(30) not null,
    source varchar(30) not null,
    decision_source varchar(32),
    character_id bigint,
    character_ids TEXT,
    scene_id bigint,
    evolution_id bigint,
    location_id bigint,
    location_name varchar(100),
    visibility varchar(20),
    title varchar(200),
    content TEXT,
    payload_json TEXT,
    importance integer,
    game_hour bigint,
    source_key varchar(100),
    cause_event_id bigint,
    correlation_id varchar(40),
    depth integer,
    event_created_at timestamp(6),
    event_updated_at timestamp(6),
    -- 归档时刻按游戏日存一份，便于「按游戏日回捞」直接命中索引
    game_day bigint,
    archived_at timestamp(6),
    primary key (id)
);

create index if not exists idx_event_archive_project_day on actor_event_archive (project_id, game_day);
create index if not exists idx_event_archive_event_id on actor_event_archive (event_id);
