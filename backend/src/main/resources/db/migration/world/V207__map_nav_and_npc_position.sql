-- V207：地图可编辑布局 + NPC 沿路移动（P1）
--
-- 背景（docs/设计文档/HolzynActor_地图可编辑布局与NPC沿路移动_设计文档_V1.0.md）：
--   旧行为是「角色位置只在浏览器里按日程线性插值」——后端不知道人在哪，
--   于是「AI 让人去哪」和「图上人在哪」是两套坐标。本次把坐标收成一份权威：
--
--   1. actor_map_feature_override —— 用户手改的建筑位置/朝向（覆盖层，不改写要素本体，
--      所以「清除手改」是零风险回滚；S3/S4 重跑后按 feature_code 重放）。
--   2. actor_npc_position       —— 角色当前坐标的唯一权威（米制，世界时钟的哪个游戏秒）。
--      写入口只有 NpcPositionService，其他模块只读（AGENTS.md 8.1 第 4 条）。
--   3. actor_npc_path           —— 一条移动轨迹（折线 + 出发/到达游戏秒 + 状态）。
--      轨迹是日志性质，按天清理；不做业务外键，便于重跑与回放。
--
-- 坐标口径：米，原点西南角，X 向东、Z 向南，0..1024（与 actor_map_feature 同源）。
-- ============================================================================

-- ---------------------------------------------------------------- 布局覆盖（手改）
create table if not exists actor_map_feature_override (
    id bigint generated by default as identity,
    project_id bigint not null,
    map_id bigint not null,
    feature_code varchar(64) not null,
    pos_x float(53) not null,
    pos_z float(53) not null,
    rotation float(53) default 0,
    door_x float(53),
    door_z float(53),
    door_dir float(53),
    revision integer default 1,
    note varchar(200),
    updated_at timestamp(6),
    primary key (id)
);
create unique index if not exists uk_map_override on actor_map_feature_override (map_id, feature_code);
create index if not exists idx_map_override_proj on actor_map_feature_override (project_id, map_id);

-- ---------------------------------------------------------------- 角色坐标（唯一权威）
create table if not exists actor_npc_position (
    id bigint generated by default as identity,
    project_id bigint not null,
    map_id bigint not null,
    npc_ref varchar(64) not null,
    npc_name varchar(100),
    x float(53) not null,
    z float(53) not null,
    heading float(53) default 0,
    indoor integer default 0,
    activity varchar(40),
    feature_code varchar(64),
    status varchar(16) default 'static',
    game_second bigint not null,
    updated_at timestamp(6),
    primary key (id)
);
create unique index if not exists uk_npc_pos on actor_npc_position (project_id, npc_ref);
create index if not exists idx_npc_pos_map on actor_npc_position (map_id, status);

-- ---------------------------------------------------------------- 移动轨迹
create table if not exists actor_npc_path (
    id bigint generated by default as identity,
    project_id bigint not null,
    map_id bigint not null,
    npc_ref varchar(64) not null,
    points_json TEXT not null,
    length_m float(53) not null,
    depart_game_second bigint not null,
    arrive_game_second bigint not null,
    from_ref varchar(64),
    to_ref varchar(64),
    reason varchar(24) not null,
    status varchar(16) not null,
    version integer default 1,
    created_at timestamp(6),
    primary key (id)
);
create index if not exists idx_npc_path_npc on actor_npc_path (project_id, npc_ref, status);
create index if not exists idx_npc_path_map on actor_npc_path (map_id, status);
