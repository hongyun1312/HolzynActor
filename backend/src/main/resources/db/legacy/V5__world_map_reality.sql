-- ============================================================================
-- V5：世界地图真实化（M6 数据回写 + 角色日程 + 环境动态 + 写实底图）
--
-- 迁移原则：
--   1. 只加列/加表，不改不删既有列——存量地图（map 1~107）仍能读，重生成时再补数据。
--   2. 「语义层 ↔ 几何层」的绑定落在 actor_map_feature.owner_home_ref + actor_npc_home.map_feature_id：
--      前者回答「这栋房子属于哪个住所」，后者回答「这个住所画在哪栋房子上」。
--   3. 角色日程（actor_npc_routine）是「让角色像真人」的最小数据面：
--      一天若干段时间 + 每段的落点（米），前端按世界时钟插值即可让角色在图上走动。
-- ============================================================================

-- ---------------------------------------------------------------- 地图本体：写实底图与契约
alter table actor_world_map add column if not exists brief_json TEXT;
alter table actor_world_map add column if not exists ambient_json TEXT;
alter table actor_world_map add column if not exists composite_path varchar(255);
alter table actor_world_map add column if not exists composite_night_path varchar(255);

-- ---------------------------------------------------------------- 要素：锚点与住所绑定
alter table actor_map_feature add column if not exists anchor_location varchar(100);
alter table actor_map_feature add column if not exists region_code varchar(64);
alter table actor_map_feature add column if not exists owner_home_ref varchar(64);
alter table actor_map_feature add column if not exists flags_json TEXT;

create index if not exists idx_map_feature_home on actor_map_feature (map_id, owner_home_ref);

-- ---------------------------------------------------------------- 住所：地图绑定与门口坐标
alter table actor_npc_home add column if not exists map_id bigint;
alter table actor_npc_home add column if not exists map_feature_id bigint;
alter table actor_npc_home add column if not exists door_x float(53);
alter table actor_npc_home add column if not exists door_z float(53);

create index if not exists idx_npc_home_map on actor_npc_home (map_id);

-- ---------------------------------------------------------------- 角色日程（家 → 工作地 → 集市 → 夜归）
create table if not exists actor_npc_routine (
    id bigint generated by default as identity,
    project_id bigint not null,
    map_id bigint not null,
    npc_ref varchar(64) not null,
    npc_name varchar(100),
    seq integer not null,
    start_minute integer not null,
    end_minute integer not null,
    place_kind varchar(24),
    place_ref varchar(100),
    feature_code varchar(64),
    pos_x float(53),
    pos_z float(53),
    activity varchar(40),
    label varchar(100),
    indoor integer,
    created_at timestamp(6),
    primary key (id)
);

create index if not exists idx_npc_routine_project on actor_npc_routine (project_id, map_id);
create index if not exists idx_npc_routine_npc on actor_npc_routine (project_id, npc_ref, seq);
