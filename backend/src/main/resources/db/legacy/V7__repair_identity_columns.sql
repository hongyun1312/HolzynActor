-- V7：修复 12 张表的 id 身份列缺失（玩家档案 500 的根因）
--
-- 背景（2026-10-23 实测定位）：
--   设置页「玩家档案」打开即空白，GET /api/player-profile 返回 HTTP 500：
--     {"code":500,...,"detail":"could not execute statement [NULL not allowed for column \"id\";
--      SQL statement: insert into actor_talk_player_profile (...,id) values (...,default) [23502-240]]"}
--   即「首次惰性创建玩家档案行」必然失败 —— 表里一行都没有，所以每次打开都是 500。
--
-- 根因（schema 漂移，不是业务代码 bug）：
--   Hibernate 对 H2 的 IDENTITY 主键生成的是 `insert ... (..., id) values (..., default)`，
--   依赖列上有 default（identity）才不报错。而这 12 张表是在「Flyway 之前」用历史
--   ddl-auto 时代建出来的，id 是裸 `bigint NOT NULL`，没有 identity；
--   后来引入 Flyway 时这些库走 baseline-on-migrate（见 application.yml 注释），
--   V1__baseline.sql 被标记为已执行而**未真正建表**，于是 V1 里的
--   `id bigint generated by default as identity` 从未落到这些库上 → 漂移固化。
--   实测 evidence（data/holzyn-actor.mv.db，2026-10-23）：
--     flyway_schema_history 第 1 行 type=BASELINE（version=1）→ V1 未执行；
--     information_schema.columns：112 个 id 列中 12 个 is_identity=NO；
--     这 12 张表当前全部 0 行（对谈/助手/决策台账的首次写入从来没能成功过）。
--
-- 影响面（不止玩家档案）：
--   下列 12 张表的**任意首行插入**都会 500；对谈会话/消息、助手会话/消息、
--   群聊成员、世界书、决策台账等等都是「一用就炸」，只是玩家档案是最先被点到的入口。
--
-- 方案：把这 12 张表的 id 列补回 `generated by default as identity`。
--   · 用 `generated by default`（不是 always）：历史库若已有行/显式写入 id 仍可插入；
--   · `alter table if exists`：老库若缺表（历史版本没建过）不会让迁移失败，
--     该表随后由 DatabaseStructureValidator 兜底建表；
--   · 幂等：H2 2.4.240 上对「已经是 identity」的列重复执行同样语句是 no-op（已实测），
--     因此全新库（V1 建表即 identity）执行本迁移不会报错；
--   · 序列起点自动接续既有最大 id（实测：已有 1,2 → 新插入得 3），不会撞主键。
--
-- 为什么不改实体：12 个实体都是 @GeneratedValue(IDENTITY)，与 V1 基线一致；
--   错的是存量库的物理结构，按「Flyway 是 schema 唯一权威」修库才是正解。
-- ============================================================================

alter table if exists actor_talk_player_profile alter column id bigint generated by default as identity;
alter table if exists actor_talk_player_relation alter column id bigint generated by default as identity;
alter table if exists actor_talk_session alter column id bigint generated by default as identity;
