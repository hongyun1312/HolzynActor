-- ============================================================================
-- V4：世界地图生成管线（S0 世界档案 → S1 地形栅格 → S2 建筑资产 → S3 路网
--     → S4 落位 → S5 合成包）
--
-- 设计原则（见 docs/设计文档/HolzynActor_世界地图生成管线_开发路径_V1.1.md §4）：
--   1. 一张地图 = actor_world_map 一行；地图内的东西全部挂在 map_id 下，重新生成
--      整张图时按 map_id 级联清理，不做跨图兼容。
--   2. 语义层（actor_world_location，V1 已有）回答「青禾家住哪」；
--      几何层（actor_map_feature）回答「那间屋子的墙在哪」。两层用 code 关联。
--   3. 全部坐标用「米」（pos_x / pos_z 为地图内米数，原点在西南角，X 向东、Z 向南），
--      格数只在渲染/寻路时由 meters_per_cell 换算——地图尺寸可变，米不变。
-- ============================================================================

-- ---------------------------------------------------------------- 地图本体
create table actor_world_map (
    id bigint generated by default as identity,
    project_id bigint not null,
    seed bigint not null,
    version integer,
    size integer not null,
    meters_per_cell float(53) not null,
    genre_profile varchar(40),
    name varchar(100),
    status varchar(20) not null,
    stage varchar(24),
    progress integer,
    params_json TEXT,
    profile_json TEXT,
    stats_json TEXT,
    terrain_path varchar(255),
    terrain_version integer,
    generated_at timestamp(6),
    created_at timestamp(6),
    updated_at timestamp(6),
    primary key (id)
);
create index idx_world_map_project on actor_world_map (project_id, status);

-- ---------------------------------------------------------------- S2 建筑资产类型
-- 「这一带该有什么房子」——由 AI 依据世界观产出（不含坐标），S4 按语义挑类型实例化。
create table actor_map_asset_type (
    id bigint generated by default as identity,
    map_id bigint not null,
    project_id bigint not null,
    code varchar(64) not null,
    name varchar(100) not null,
    category varchar(32) not null,
    kind varchar(24) not null,
    base_w float(53),
    base_d float(53),
    floors_min integer,
    floors_max integer,
    wall_color varchar(16),
    roof_color varchar(16),
    roof_shape varchar(24),
    material varchar(24),
    style_tags varchar(200),
    weight integer,
    forbidden integer,
    description TEXT,
    sort_order integer,
    created_at timestamp(6),
    primary key (id)
);
create index idx_map_asset_type_map on actor_map_asset_type (map_id, category);

-- ---------------------------------------------------------------- 建筑聚落（院落/街区）
-- 一个院落 = 主体建筑 + 附属棚屋 + 围墙 + 门；一条街 = 若干院落沿路排布。
create table actor_map_feature_group (
    id bigint generated by default as identity,
    map_id bigint not null,
    project_id bigint not null,
    code varchar(64) not null,
    name varchar(100),
    kind varchar(24) not null,
    center_x float(53) not null,
    center_z float(53) not null,
    radius float(53),
    rotation float(53),
    style_code varchar(40),
    description TEXT,
    sort_order integer,
    created_at timestamp(6),
    primary key (id)
);
create index idx_map_group_map on actor_map_feature_group (map_id, kind);

-- ---------------------------------------------------------------- 地图要素（建筑/农田/林地/码头/桥…）
create table actor_map_feature (
    id bigint generated by default as identity,
    map_id bigint not null,
    project_id bigint not null,
    group_id bigint,
    asset_type_id bigint,
    asset_code varchar(64),
    code varchar(64) not null,
    name varchar(100),
    category varchar(32),
    kind varchar(24) not null,
    pos_x float(53) not null,
    pos_z float(53) not null,
    size_w float(53),
    size_d float(53),
    rotation float(53),
    height float(53),
    floors integer,
    base_elevation float(53),
    wall_color varchar(16),
    roof_color varchar(16),
    roof_shape varchar(24),
    door_x float(53),
    door_z float(53),
    door_dir float(53),
    polygon_json TEXT,
    footprint_json TEXT,
    semantic_json TEXT,
    location_code varchar(64),
    residency integer,
    importance integer,
    sort_order integer,
    created_at timestamp(6),
    updated_at timestamp(6),
    primary key (id)
);
create index idx_map_feature_map on actor_map_feature (map_id, kind);
create index idx_map_feature_group on actor_map_feature (group_id);
create index idx_map_feature_loc on actor_map_feature (map_id, location_code);

-- ---------------------------------------------------------------- 道路（折线）
create table actor_map_road (
    id bigint generated by default as identity,
    map_id bigint not null,
    project_id bigint not null,
    code varchar(64) not null,
    name varchar(100),
    kind varchar(24) not null,
    level varchar(16),
    width float(53),
    surface varchar(24),
    path_json TEXT not null,
    from_feature_id bigint,
    to_feature_id bigint,
    connects_json TEXT,
    length float(53),
    bridge_over varchar(24),
    sort_order integer,
    created_at timestamp(6),
    primary key (id)
);
create index idx_map_road_map on actor_map_road (map_id, kind);

-- ---------------------------------------------------------------- 地块（S4 落位的「格子」）
create table actor_map_parcel (
    id bigint generated by default as identity,
    map_id bigint not null,
    project_id bigint not null,
    group_id bigint,
    code varchar(64) not null,
    kind varchar(24) not null,
    center_x float(53) not null,
    center_z float(53) not null,
    area float(53),
    buildable float(53),
    polygon_json TEXT,
    feature_id bigint,
    road_code varchar(64),
    sort_order integer,
    created_at timestamp(6),
    primary key (id)
);
create index idx_map_parcel_map on actor_map_parcel (map_id, kind);
